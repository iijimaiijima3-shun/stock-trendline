# Reverse mapping: name keyword -> list of tickers
def search_by_name(query: str) -> list[tuple[str, str]]:
    """
    Search tickers by partial Japanese company name.
    Returns list of (ticker, name) sorted by relevance.
    """
    q = query.strip().lower()
    if not q:
        return []

    results = []
    for ticker, name in TICKER_TO_NAME.items():
        if q in name.lower() or q in ticker.lower().replace(".t", ""):
            results.append((ticker, name))

    # Exact prefix match ranked first
    results.sort(key=lambda x: (not x[1].lower().startswith(q), x[1]))
    return results


def get_name(ticker: str) -> str:
    """Return Japanese name for ticker, fallback to ticker string."""
    return TICKER_TO_NAME.get(ticker, ticker)
